"""
CinePulse AI - What-If Demand Simulator Service
Evaluates counterfactual scenario adjustments and provides causal governance.
"""

from typing import Any, Dict
from backend.app.schemas.show import (
    ShowPredictionInput,
    SimulationResponse,
    SimulationDelta,
    ShowPredictionOutput,
)
from backend.app.services.model_service import get_predictor


class SimulatorService:
    def __init__(self):
        self.predictor = get_predictor()

    def simulate_scenario(self, base_input: ShowPredictionInput, sim_input: ShowPredictionInput) -> SimulationResponse:
        base_dict = base_input.model_dump()
        sim_dict = sim_input.model_dump()

        # Run real model inference for both scenarios
        base_pred_dict = self.predictor.predict_single_show(base_dict, include_explanation=True)
        sim_pred_dict = self.predictor.predict_single_show(sim_dict, include_explanation=True)

        base_res = ShowPredictionOutput(**base_pred_dict)
        sim_res = ShowPredictionOutput(**sim_pred_dict)

        # Compute deltas
        d_tickets = sim_res.predicted_tickets_sold - base_res.predicted_tickets_sold
        d_rev = round(sim_res.estimated_ticket_revenue - base_res.estimated_ticket_revenue, 2)
        d_occ = round(sim_res.predicted_occupancy_percentage - base_res.predicted_occupancy_percentage, 1)

        pct_tickets = round((d_tickets / max(1, base_res.predicted_tickets_sold)) * 100.0, 1)
        pct_rev = round((d_rev / max(1.0, base_res.estimated_ticket_revenue)) * 100.0, 1)

        deltas = SimulationDelta(
            delta_tickets=d_tickets,
            delta_revenue=d_rev,
            delta_occupancy_pct=d_occ,
            percentage_change_tickets=pct_tickets,
            percentage_change_revenue=pct_rev,
        )

        # Clear causal disclaimer & operational takeaway
        causal_disclaimer = (
            "CAUSAL NOTICE: Predictions generated by the XGBoost regression pipeline represent "
            "conditional statistical associations learned from observational multiplex data. "
            "These projections assume all other unobserved environmental factors remain stationary "
            "and do NOT constitute an unconfounded randomized causal guarantee. Price changes or "
            "screen transfers should be validated alongside real-time pre-booking velocity."
        )

        # Construct managerial takeaway
        if d_rev > 0 and d_tickets >= 0:
            takeaway = (
                f"Favorable Shift: Simulated adjustments yield an estimated uplift of +{d_tickets} tickets "
                f"and +₹{d_rev:,.2f} projected revenue (+{pct_rev}%). Screen capacity comfortably supports this adjustment."
            )
        elif d_rev > 0 and d_tickets < 0:
            takeaway = (
                f"Margin Trade-off: Higher pricing offsets lower attendance (-{abs(d_tickets)} tickets), "
                f"generating a net revenue gain of +₹{d_rev:,.2f}. Ensure concession/F&B spend is factored into net margins."
            )
        elif d_rev < 0 and d_tickets > 0:
            takeaway = (
                f"Volume over Revenue: Ticket volume expands (+{d_tickets} tickets) but lower ticket yield "
                f"decreases direct admissions revenue by -₹{abs(d_rev):,.2f}. Viable if concession cross-selling is high."
            )
        else:
            takeaway = (
                f"Downside Advisory: Simulated configuration results in a decline of {d_tickets} tickets "
                f"and -₹{abs(d_rev):,.2f} revenue. Recommend retaining original scheduling parameters."
            )

        return SimulationResponse(
            base_result=base_res,
            simulated_result=sim_res,
            differences=deltas,
            causal_disclaimer=causal_disclaimer,
            operational_takeaway=takeaway,
        )

